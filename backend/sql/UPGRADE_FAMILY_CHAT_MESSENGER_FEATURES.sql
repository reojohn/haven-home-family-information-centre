-- Haven Home Family Chat v2: upgrade an EXISTING private family chat schema.
-- Run once in Supabase SQL Editor BEFORE deploying the new backend.
-- This script preserves all existing family messages and read cursors.
BEGIN;

ALTER TABLE public.family_chat_messages
  ADD COLUMN IF NOT EXISTS reply_to_id integer REFERENCES public.family_chat_messages(id),
  ADD COLUMN IF NOT EXISTS edited_at timestamp without time zone,
  ADD COLUMN IF NOT EXISTS deleted_at timestamp without time zone;

CREATE TABLE IF NOT EXISTS public.family_chat_reactions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id integer NOT NULL REFERENCES public.households(id),
  message_id integer NOT NULL REFERENCES public.family_chat_messages(id),
  user_id integer NOT NULL REFERENCES public.users(id),
  emoji varchar(10) NOT NULL,
  CONSTRAINT uq_family_chat_reaction_user UNIQUE (message_id, user_id),
  CONSTRAINT ck_family_chat_reaction_emoji CHECK (emoji IN ('❤️','😂','👍'))
);
CREATE INDEX IF NOT EXISTS ix_family_chat_reactions_household_id ON public.family_chat_reactions(household_id);
CREATE INDEX IF NOT EXISTS ix_family_chat_reactions_message_id ON public.family_chat_reactions(message_id);

CREATE TABLE IF NOT EXISTS public.family_chat_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id integer NOT NULL REFERENCES public.households(id),
  message_id integer NOT NULL REFERENCES public.family_chat_messages(id),
  created_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_family_chat_changes_household_id ON public.family_chat_changes(household_id);
CREATE INDEX IF NOT EXISTS ix_family_chat_changes_household_cursor ON public.family_chat_changes(household_id,id);

CREATE TABLE IF NOT EXISTS public.family_chat_presence (
  user_id integer PRIMARY KEY REFERENCES public.users(id),
  household_id integer NOT NULL REFERENCES public.households(id),
  last_seen_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_family_chat_presence_household_id ON public.family_chat_presence(household_id);

-- The browser uses only the existing cookie-authenticated FastAPI routes.
-- No direct PostgREST access is granted to anonymous or authenticated roles.
ALTER TABLE public.family_chat_reactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.family_chat_changes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.family_chat_presence ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.family_chat_reactions, public.family_chat_changes, public.family_chat_presence FROM PUBLIC;
DO $$
DECLARE role_name text;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=role_name) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.family_chat_reactions, public.family_chat_changes, public.family_chat_presence FROM %I', role_name);
    END IF;
  END LOOP;
END $$;
COMMIT;
