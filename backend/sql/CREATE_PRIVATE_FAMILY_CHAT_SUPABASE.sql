-- Haven Home: private Family Chat schema for an EXISTING Supabase project.
-- Run as the database owner in the Supabase SQL Editor before deploying.
-- This script creates only the two new chat tables and indexes.
-- All message access happens through the authenticated FastAPI backend.
-- No anon/authenticated PostgREST policies are granted.

BEGIN;

CREATE TABLE IF NOT EXISTS public.family_chat_messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id integer NOT NULL REFERENCES public.households(id),
  sender_user_id integer REFERENCES public.users(id),
  sender_name varchar(100) NOT NULL,
  body varchar(2000) NOT NULL,
  client_nonce varchar(64),
  created_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uq_family_chat_client_nonce UNIQUE (household_id, sender_user_id, client_nonce)
);
CREATE INDEX IF NOT EXISTS ix_family_chat_household_cursor
  ON public.family_chat_messages (household_id, id);

CREATE TABLE IF NOT EXISTS public.family_chat_reads (
  user_id integer PRIMARY KEY REFERENCES public.users(id),
  household_id integer NOT NULL REFERENCES public.households(id),
  last_read_id integer NOT NULL DEFAULT 0,
  updated_at timestamp without time zone NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS ix_family_chat_reads_household_id
  ON public.family_chat_reads (household_id);

ALTER TABLE public.family_chat_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.family_chat_reads ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.family_chat_messages, public.family_chat_reads FROM PUBLIC;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.family_chat_messages, public.family_chat_reads FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON public.family_chat_messages, public.family_chat_reads FROM authenticated;
  END IF;
END;
$$;
COMMIT;

-- No existing households, users, bills, tasks, or messages are modified.
-- If the API database user doesn't own these tables, grant it access separately
-- using a trusted server role; do not grant anon or authenticated direct access.
