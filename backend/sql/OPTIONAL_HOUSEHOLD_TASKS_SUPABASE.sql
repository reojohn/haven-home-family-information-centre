-- Haven Home / Household Tasks & Chores
-- OPTIONAL: run in the correct Supabase project ONLY if the FastAPI backend
-- cannot create its new table at startup. Back up before making schema changes.
-- Does not delete or modify any existing electricity, bill, or family data.
CREATE TABLE IF NOT EXISTS public.household_tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id INTEGER NOT NULL REFERENCES public.households(id),
  title VARCHAR(120) NOT NULL,
  description TEXT NOT NULL,
  category VARCHAR(30) NOT NULL,
  priority VARCHAR(10) NOT NULL,
  due_date VARCHAR(10) NOT NULL,
  assigned_to INTEGER REFERENCES public.users(id),
  created_by INTEGER NOT NULL REFERENCES public.users(id),
  status VARCHAR(20) NOT NULL,
  repeat VARCHAR(10) NOT NULL,
  next_created BOOLEAN NOT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  completed_at TIMESTAMP WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_household_tasks_household_id ON public.household_tasks(household_id);
-- This project uses session-authenticated FastAPI for all reads and writes.
-- Keep the tasks table inaccessible to Supabase's public Data API roles.
ALTER TABLE public.household_tasks ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.household_tasks FROM anon, authenticated;
-- Newly created sequences are also private to the backend database role.
REVOKE ALL PRIVILEGES ON SEQUENCE public.household_tasks_id_seq FROM anon, authenticated;
